// 💡 [혁신 1] 스마트 자동 완성 로직 (숫자/영문 우선! m5 -> 90-M5 찰떡 변환)
const autoFormatGlasuritCode = (input: string) => {
    let val = input.toUpperCase().replace(/[^A-Z0-9/]/g, '');
    if (!val) return val;

    // 대표님 맞춤형 BASF 스마트 퀵 매칭 (치기 귀찮은 거 위주로 세팅)
    if (val === 'M4') return '90-M4';
    if (val === 'M5') return '90-M5';
    if (val === 'M1') return '90-M1';
    if (val === 'E3') return '93-E3';
    if (val === 'E3SLOW' || val === 'SLOW') return '93-E3 Slow';
    if (val === 'M3') return '90-M3';
    if (val === 'M20') return '90-M20';
    if (val === 'M9900' || val === '9900') return '90-M99/00';
    if (val === 'M9902' || val === '9902') return '90-M99/02';
    if (val === 'M9904' || val === '9904') return '90-M99/04';
    
    // A031 치면 90-A031 로 자동 완성
    if (/^[A-Z]\d+$/.test(val)) return `90-${val}`;

    // 위에서 안 걸리면 원래 하던 방식대로 검색
    const keys = Object.keys(TONER_DB);
    let match = keys.find(k => k.replace(/-/g, '') === val.replace(/-/g, ''));
    if (match) return match;
    match = keys.find(k => k.split('-')[1] === val);
    if (match) return match;
    match = keys.find(k => k.split('-')[1]?.replace(/\//g, '') === val);
    if (match) return match;
    
    return input.toUpperCase(); 
};

